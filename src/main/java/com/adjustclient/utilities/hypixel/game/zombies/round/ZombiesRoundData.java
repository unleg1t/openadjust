    private static void add(Int2ObjectOpenHashMap<ZombiesRoundTiming[]> table, int round, int... ticks) {
        ZombiesRoundTiming[] timings = new ZombiesRoundTiming[ticks.length];
        for (int i = 0; i < ticks.length; i++)
            timings[i] = new ZombiesRoundTiming(ticks[i], ZombiesBoss.NONE, ZombiesBoss.NONE, ZombiesBoss.NONE);
        table.put(round, timings);
    }
    private static void tag(Int2ObjectOpenHashMap<ZombiesRoundTiming[]> table, int round, int index,
            ZombiesBoss normal, ZombiesBoss hard, ZombiesBoss rip) {
        ZombiesRoundTiming old = table.get(round)[index];
        table.get(round)[index] = new ZombiesRoundTiming(old.ticks(), normal, hard, rip);
    }
